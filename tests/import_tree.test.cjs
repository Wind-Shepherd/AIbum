const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const source = fs.readFileSync('web/atelier.js','utf8');
const moveFunction = source.slice(source.indexOf('function canMoveImport'),source.indexOf('function clearImport'));
const context = vm.createContext({importNodes:[{id:'a',parent:null},{id:'b',parent:'a'},{id:'c',parent:'b'},{id:'d',parent:null}]});
vm.runInContext(moveFunction,context);
assert.equal(context.canMoveImport('a','a'),false);
assert.equal(context.canMoveImport('a','c'),false);
assert.equal(context.canMoveImport('b','c'),false);
assert.equal(context.canMoveImport('c','a'),true);
assert.equal(context.canMoveImport('b','d'),true);
assert.equal(context.canMoveImport('b',null),true);
context.notice=()=>{};
context.moveImportSelection(['a','b'],'d');
assert.equal(context.importNodes.find(n=>n.id==='a').parent,'d');
assert.equal(context.importNodes.find(n=>n.id==='b').parent,'a');
context.moveImportSelection(['d'],'c');
assert.equal(context.importNodes.find(n=>n.id==='d').parent,null);
console.log('Import hierarchy: self/descendant moves rejected, valid moves accepted.');
